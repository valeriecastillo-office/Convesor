    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String nombreBuscado = txtBuscarNombre.getText().trim();

        if (nombreBuscado.isEmpty()) {
            JOptionPane.showMessageDialog(this, 
                "Por favor, ingrese un nombre para buscar.", 
                "Aviso", 
                JOptionPane.WARNING_MESSAGE);
        } else {
           
            String telefono = miAgenda.busquedaPersona(nombreBuscado);

            
            if (telefono != null) {
                lblResultado.setText("Teléfono: " + telefono);
            } else {
                lblResultado.setText("Contacto no encontrado");
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed

        String nombre = txtNombre.getText().trim();
        String telefono = txtTelefono.getText().trim();
        if (nombre.isEmpty() || telefono.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Debe ingresar el nombre y el teléfono.",
                    "Campos vacíos",
                    JOptionPane.WARNING_MESSAGE);
        } 
        else {

            Contacto c = new Contacto(nombre, telefono);
            miAgenda.guardarNuevosContactos(c);
            txtNombre.setText("");
            txtTelefono.setText("");
            txtNombre.requestFocus();

            JOptionPane.showMessageDialog(this,
                    "Contacto guardado con éxito.",
                    "Éxito",
                    JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

